/* ---------- 4) Wrappers @Operation ---------- */
PRINT N'--- 4) Ensure Detail apply wrappers have @Operation ---';

DECLARE @wrap sysname, @sql nvarchar(max);
DECLARE wcur CURSOR LOCAL FAST_FORWARD FOR
SELECT v.Name FROM (VALUES
    (N'SyncApply_PurchaseDetail'),
    (N'SyncApply_TransferDetail'),
    (N'SyncApply_SaleDetail')
) v(Name);

OPEN wcur;
FETCH NEXT FROM wcur INTO @wrap;
WHILE @@FETCH_STATUS = 0
BEGIN
    IF OBJECT_ID(N'dbo.' + @wrap, N'P') IS NOT NULL
       AND OBJECT_DEFINITION(OBJECT_ID(N'dbo.' + @wrap)) LIKE N'%@Operation%'
        PRINT N'  ' + @wrap + N' OK';
    ELSE IF OBJECT_ID(N'dbo.SyncApply_Generic', N'P') IS NOT NULL
    BEGIN
        IF OBJECT_ID(N'dbo.' + @wrap, N'P') IS NOT NULL
            EXEC(N'DROP PROCEDURE dbo.' + @wrap);

        SET @sql = N'
CREATE PROCEDURE dbo.' + @wrap + N'
    @Source varchar(10),
    @PayloadJson nvarchar(max),
    @RemoteModifiedAt datetime2(3),
    @PrimaryKeyJson nvarchar(500),
    @OutboxID bigint = NULL,
    @Operation char(1) = NULL,
    @ConflictLogged bit OUTPUT,
    @Applied bit OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    EXEC dbo.SyncApply_Generic
        @Source = @Source,
        @TableName = N''' + REPLACE(@wrap, N'SyncApply_', N'') + N''',
        @PayloadJson = @PayloadJson,
        @PrimaryKeyJson = @PrimaryKeyJson,
        @RemoteModifiedAt = @RemoteModifiedAt,
        @Operation = @Operation,
        @OutboxID = @OutboxID,
        @ConflictLogged = @ConflictLogged OUTPUT,
        @Applied = @Applied OUTPUT;
END';
        EXEC(@sql);
        PRINT N'  ' + @wrap + N' created (+@Operation)';
    END
    ELSE
        PRINT N'  ' + @wrap + N' SKIP — SyncApply_Generic missing';

    FETCH NEXT FROM wcur INTO @wrap;
END
CLOSE wcur; DEALLOCATE wcur;
GO

/* ---------- 5) Requeue C2L Op=D ---------- */
PRINT N'--- 5) Requeue C2L *Detail Op=D (last 2 days) ---';
DECLARE @since datetime2(3) = DATEADD(day, -2, SYSUTCDATETIME());

UPDATE dbo.SyncOutbox
SET Status = N'Pending',
    AttemptCount = 0,
    LastError = NULL,
    SyncedAt = NULL,
    SyncModifiedAt = SYSUTCDATETIME()
WHERE Direction = N'C2L'
  AND TableName LIKE N'%Detail'
  AND Operation = N'D'
  AND Status IN (N'Synced', N'Conflict', N'DeadLetter', N'Syncing')
  AND CreatedAt >= @since;
PRINT N'Requeued: ' + CAST(@@ROWCOUNT AS nvarchar(20));
GO

