/* ---------- 0) Apply markers ---------- */
PRINT N'--- 0) SyncApply markers ---';
SELECT
  CASE WHEN OBJECT_ID(N'dbo.SyncApply_Generic', N'P') IS NULL THEN N'MISSING'
       WHEN OBJECT_DEFINITION(OBJECT_ID(N'dbo.SyncApply_Generic')) LIKE N'%hardDeleteDetail%'
