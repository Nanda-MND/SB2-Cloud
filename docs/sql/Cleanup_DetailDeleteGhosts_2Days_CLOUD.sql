/*
  ============================================================================
  CLOUD warehouse — cleanup Detail hard-delete sync ghosts (last 2 days)
  ============================================================================
  Scope: yesterday + today (UTC), all *Detail tables.

  Does:
    1) Hard-DELETE IsDeleted=1 ghosts (last 2 days)
    2) Hard-DELETE rows whose IDs appear in Cloud C2L Op=D outbox (last 2 days)
       — covers soft-apply that left IsDeleted=0 wrongly or failed hard-delete
    3) Requeue C2L Op=D
    4) Ensure SyncApply_PurchaseDetail / TransferDetail / SaleDetail have @Operation

  Also paste SqlBatch generated by LOCAL Cleanup_DetailDeleteGhosts_2Days_LOCAL.sql
  (section 3) into this session if Local→Cloud orphans remain.
*/

